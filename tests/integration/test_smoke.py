# 7. FK disable/enable cycle
# ---------------------------------------------------------------------------


def test_fk_disable_enable_cycle_around_load(
    oracle_conn: object,
    fresh_schemas: tuple[str, str],
    oracle_dsn: tuple[str, str, str],
) -> None:
    from pydantic import SecretStr

    from oracle_schema_refresh.config import RefreshConfig
    from oracle_schema_refresh.endpoints import Endpoint
    from oracle_schema_refresh.engine import RefreshEngine

    src, tgt = fresh_schemas
    cur = oracle_conn.cursor()  # type: ignore[attr-defined]

    # Source: parent + child with FK.
    cur.execute(
        f'CREATE TABLE "{src}"."PARENT" (id NUMBER PRIMARY KEY, label VARCHAR2(20))'
    )
    cur.execute(
        f'CREATE TABLE "{src}"."CHILD" ('
        f"  id NUMBER PRIMARY KEY,"
        f"  parent_id NUMBER NOT NULL,"
        f'  CONSTRAINT child_fk FOREIGN KEY (parent_id) REFERENCES "{src}"."PARENT"(id)'
        f")"
    )
    cur.executemany(
        f'INSERT INTO "{src}"."PARENT" VALUES (:1, :2)',
        [(i, f"p{i}") for i in range(5)],
    )
    cur.executemany(
        f'INSERT INTO "{src}"."CHILD" VALUES (:1, :2)',
        [(i, i % 5) for i in range(15)],
    )
    oracle_conn.commit()  # type: ignore[attr-defined]

    user, password, dsn = oracle_dsn
    ep = Endpoint(name="x", dsn=dsn, username=user, password=SecretStr(password))
    cfg = RefreshConfig(
        source_schema=src,
        target_schema=tgt,
        tables=["CHILD"],  # FK parent discovery should pull in PARENT
        auto_include_fk_parents=True,
    )
    result = RefreshEngine(ep, cfg).run(dry_run=False)

    assert result.success is True
    statuses = {r.table_name: r.status for r in result.table_results}
    assert statuses == {"PARENT": "ok", "CHILD": "ok"}
    # Topological order: parent before child.
    assert result.table_order == ["PARENT", "CHILD"]
