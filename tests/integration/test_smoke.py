# ---------------------------------------------------------------------------


def test_connection_works(oracle_conn: object) -> None:
    """Sanity: we can SELECT 1 against the container."""
    cur = oracle_conn.cursor()  # type: ignore[attr-defined]
    cur.execute("SELECT 1 FROM dual")
    assert cur.fetchone() == (1,)


def test_endpoint_connect_via_endpoint(oracle_endpoint: object) -> None:
    conn = oracle_endpoint.connect()  # type: ignore[attr-defined]
    try:
        cur = conn.cursor()
        cur.execute("SELECT user FROM dual")
        row = cur.fetchone()
        assert row[0]
    finally:
        conn.close()


