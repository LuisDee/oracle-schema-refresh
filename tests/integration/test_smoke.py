"""Smoke tests against a real Oracle (testcontainers or $ORACDB_TEST_DSN).

Every test is marked ``@pytest.mark.integration``. Unit-only runs
(``pytest -q``) skip the whole directory by default; opt in with
``pytest -m integration``.

These are the contracts the mock-based unit suite can't prove:
1. ``CREATE TABLE oracdb$jobs`` and ``oracdb$tables`` actually work,
   and ``ensure_schema`` is genuinely idempotent.
2. ``AS OF SCN :scn`` reads return a consistent snapshot under
   concurrent writes.
3. ``ALTER SEQUENCE … RESTART`` works against 23c-free.
4. End-to-end ``oracdb plan`` → ``run`` → ``status`` → ``verify``.
5. FK disable/enable cycle is respected.
"""
from __future__ import annotations

import pytest

pytestmark = pytest.mark.integration


