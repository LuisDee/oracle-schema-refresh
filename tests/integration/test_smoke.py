# 5. ALTER SEQUENCE RESTART on 23c
# ---------------------------------------------------------------------------


def test_alter_sequence_restart_works_on_23c(oracle_conn: object) -> None:
    cur = oracle_conn.cursor()  # type: ignore[attr-defined]
    cur.execute("CREATE SEQUENCE oracdb_test_seq START WITH 1 INCREMENT BY 1")
    try:
        cur.execute("SELECT oracdb_test_seq.NEXTVAL FROM dual")
        cur.execute("SELECT oracdb_test_seq.NEXTVAL FROM dual")
        cur.execute("ALTER SEQUENCE oracdb_test_seq RESTART START WITH 100")
        cur.execute("SELECT oracdb_test_seq.NEXTVAL FROM dual")
        assert cur.fetchone()[0] == 100
    finally:
        cur.execute("DROP SEQUENCE oracdb_test_seq")


# ---------------------------------------------------------------------------
# 6. oracdb plan → run → status → verify end-to-end
# ---------------------------------------------------------------------------


def test_oracdb_pipeline_end_to_end(
    oracle_conn: object,
    fresh_schemas: tuple[str, str],
    oracle_dsn: tuple[str, str, str],
    tmp_path,  # pytest builtin
) -> None:
    """Exercise the full plan / run / status / verify flow via the
    Click CLI runner so we're going through the public interface."""
    import json
    import os

    from click.testing import CliRunner

    from oracle_schema_refresh.oracdb_cli import oracdb

    src, tgt = fresh_schemas
    _populate_source(oracle_conn, src, n_rows=10)

    user, password, dsn = oracle_dsn

    # Isolate the registry + ORACDB_HOME under tmp_path.
    env = {
        **os.environ,
        "ORACDB_REGISTRY": str(tmp_path / "endpoints.yaml"),
        "ORACDB_HOME": str(tmp_path / ".oracdb"),
    }
    runner = CliRunner()

    # register the same endpoint as source and target — same instance.
    r = runner.invoke(
        oracdb,
        ["endpoints", "add", "test",
         "--dsn", dsn, "--user", user, "--password", password],
        env=env,
    )
    assert r.exit_code == 0, r.output

    # plan
    r = runner.invoke(
        oracdb,
        [
            "plan",
            "--from", "test", "--to", "test",
            "--source-schema", src, "--target-schema", tgt,
            "--tables", "PEOPLE",
            "--no-auto-fk",
            "--json",
        ],
        env=env,
    )
    assert r.exit_code == 0, r.output
    plan_env = json.loads(r.output)
    job_id = plan_env["job_id"]
    assert plan_env["data"]["table_order"] == ["PEOPLE"]

    # run (foreground)
    r = runner.invoke(oracdb, ["run", job_id, "--json"], env=env)
    assert r.exit_code == 0, r.output

    # status
    r = runner.invoke(oracdb, ["status", job_id, "--json"], env=env)
    assert r.exit_code == 0, r.output
    status_env = json.loads(r.output)
    assert status_env["data"]["status"] == "DONE"

    # verify
    r = runner.invoke(oracdb, ["verify", job_id, "--json"], env=env)
    assert r.exit_code == 0, r.output
    verify_env = json.loads(r.output)
    assert verify_env["data"]["all_match"] is True


