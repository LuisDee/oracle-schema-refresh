def test_ensure_schema_creates_tables_and_is_idempotent(
    oracle_conn: object,
) -> None:
    from oracle_schema_refresh.state import schema as state_schema

    state_schema.ensure_schema(oracle_conn)  # type: ignore[arg-type]
    state_schema.ensure_schema(oracle_conn)  # idempotent

    cur = oracle_conn.cursor()  # type: ignore[attr-defined]
    cur.execute(
        "SELECT table_name FROM user_tables WHERE table_name IN "
        "('ORACDB$JOBS','ORACDB$TABLES')"
    )
    names = {row[0] for row in cur.fetchall()}
    assert names == {"ORACDB$JOBS", "ORACDB$TABLES"}

    # Clean up
    cur.execute("DROP TABLE oracdb$tables CASCADE CONSTRAINTS PURGE")
    cur.execute("DROP TABLE oracdb$jobs CASCADE CONSTRAINTS PURGE")
    oracle_conn.commit()  # type: ignore[attr-defined]


# ---------------------------------------------------------------------------
# 3. end-to-end same-instance refresh against fresh schemas
# ---------------------------------------------------------------------------


def _populate_source(
    oracle_conn: object, src_schema: str, n_rows: int = 50
) -> None:
    cur = oracle_conn.cursor()  # type: ignore[attr-defined]
    cur.execute(
        f'CREATE TABLE "{src_schema}"."PEOPLE" ('
        f"  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
        f"  name VARCHAR2(100),"
        f"  age NUMBER"
        f")"
    )
    cur.executemany(
        f'INSERT INTO "{src_schema}"."PEOPLE" (name, age) VALUES (:1, :2)',
        [(f"person_{i}", 20 + i % 60) for i in range(n_rows)],
    )
    oracle_conn.commit()  # type: ignore[attr-defined]


def test_same_instance_refresh_end_to_end(
    oracle_conn: object, fresh_schemas: tuple[str, str], oracle_dsn: tuple[str, str, str]
) -> None:
    """schema-refresh path (legacy CLI's engine) copies PEOPLE → target."""
    from pydantic import SecretStr

    from oracle_schema_refresh.config import RefreshConfig
    from oracle_schema_refresh.endpoints import Endpoint
    from oracle_schema_refresh.engine import RefreshEngine

    src, tgt = fresh_schemas
    _populate_source(oracle_conn, src, n_rows=25)

    user, password, dsn = oracle_dsn
    ep = Endpoint(name="x", dsn=dsn, username=user, password=SecretStr(password))
    cfg = RefreshConfig(
        source_schema=src,
        target_schema=tgt,
        tables=["PEOPLE"],
        auto_include_fk_parents=False,
    )
    engine = RefreshEngine(ep, cfg)
    result = engine.run(dry_run=False)

    assert result.success is True
    r = result.table_results[0]
    assert r.status == "ok"
    assert r.rows_source == 25
    assert r.rows_loaded == 25
    assert r.match is True
    # Identity sequence on the new IDENTITY column should have been reset.
    assert r.sequences_reset, "expected the identity-backed sequence to reset"


# ---------------------------------------------------------------------------
# 4. AS OF SCN consistent read under concurrent writes
# ---------------------------------------------------------------------------


def test_as_of_scn_sees_snapshot_under_concurrent_insert(
    oracle_conn: object, fresh_schemas: tuple[str, str], oracle_dsn: tuple[str, str, str]
) -> None:
    """Capture SCN, INSERT a new row, then read AS OF SCN — must NOT see
    the new row. Proves Flashback Query is doing what we rely on."""
    import oracledb

    src, _tgt = fresh_schemas
    cur = oracle_conn.cursor()  # type: ignore[attr-defined]
    cur.execute(
        f'CREATE TABLE "{src}"."T" (id NUMBER PRIMARY KEY, v VARCHAR2(20))'
    )
    cur.executemany(
        f'INSERT INTO "{src}"."T" VALUES (:1, :2)',
        [(i, f"v{i}") for i in range(10)],
    )
    oracle_conn.commit()  # type: ignore[attr-defined]

    cur.execute("SELECT current_scn FROM v$database")
    scn = int(cur.fetchone()[0])

    # Race: insert a new row AFTER the snapshot.
    user, password, dsn = oracle_dsn
    second = oracledb.connect(user=user, password=password, dsn=dsn)
    try:
        c2 = second.cursor()
        c2.execute(f'INSERT INTO "{src}"."T" VALUES (999, :v)', v="post-scn")
        second.commit()
    finally:
        second.close()

    cur.execute(f'SELECT COUNT(*) FROM "{src}"."T" AS OF SCN :scn', scn=scn)
    snapshot_count = int(cur.fetchone()[0])
    cur.execute(f'SELECT COUNT(*) FROM "{src}"."T"')
    current_count = int(cur.fetchone()[0])

    assert snapshot_count == 10
    assert current_count == 11


